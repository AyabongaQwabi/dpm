const PLATFORM_MAP = new Map(PLATFORMS.map((p) => [p.name, p]))

interface Props {
  fieldKey: string
  label: string
  isRequired: boolean
  saved: SocialLink[]
}

export function SocialLinksField({ fieldKey, label, isRequired, saved }: Props) {
  const [links, setLinks] = useState<SocialLink[]>(
    saved.length > 0 ? saved : []
  )

  function add() {
    const used = new Set(links.map((l) => l.platform))
    const next = PLATFORMS.find((p) => !used.has(p.name))?.name ?? 'Website'
    setLinks((prev) => [...prev, { platform: next, url: '' }])
  }

  function remove(i: number) {
    setLinks((prev) => prev.filter((_, idx) => idx !== i))
  }

  function update(i: number, key: keyof SocialLink, val: string) {
    setLinks((prev) => prev.map((l, idx) => idx === i ? { ...l, [key]: val } : l))
  }

  const valid = links.filter((l) => l.url.trim())

  return (
    <div className="space-y-3">
      <div className="flex items-center justify-between">
        <label className="text-sm font-medium text-foreground">
          {label}
          {isRequired && <span className="text-destructive ml-0.5">*</span>}
        </label>
        <button
          type="button"
          onClick={add}
          className="inline-flex items-center gap-1 rounded-full border border-primary-accent/40 bg-primary-accent/10 px-3 py-1 text-xs font-semibold text-primary-accent hover:bg-primary-accent/20 transition-colors cursor-pointer"
        >
          <svg xmlns="http://www.w3.org/2000/svg" className="h-3.5 w-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M12 4.5v15m7.5-7.5h-15" />
          </svg>
          Add
        </button>
      </div>

      <input type="hidden" name={`__${fieldKey}`} value={JSON.stringify(valid)} />

      {links.length === 0 && (
        <div className="rounded-[var(--radius)] border border-dashed border-border bg-muted/30 px-5 py-8 text-center">
          <p className="text-sm text-muted-foreground">No social links yet.</p>
          <p className="text-xs text-muted-foreground/70 mt-1">Add your profiles to help customers find and trust you.</p>
        </div>
      )}

      <div className="space-y-2">
        {links.map((link, i) => {
          const meta = PLATFORM_MAP.get(link.platform)
          return (
            <div key={i} className="group flex items-center gap-2">
              <div className="flex flex-1 items-center gap-3 rounded-[var(--radius)] border border-border bg-card px-3 py-3 shadow-sm">
                {/* Platform icon */}
                <div
                  className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full"
                  style={{ backgroundColor: meta ? `${meta.color}15` : '#f3f4f6', color: meta?.color ?? '#6b7280' }}
                >
                  {meta?.icon ?? (
                    <svg xmlns="http://www.w3.org/2000/svg" className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
                      <path strokeLinecap="round" strokeLinejoin="round" d="M13.19 8.688a4.5 4.5 0 011.242 7.244l-4.5 4.5a4.5 4.5 0 01-6.364-6.364l1.757-1.757m13.35-.622l1.757-1.757a4.5 4.5 0 00-6.364-6.364l-4.5 4.5a4.5 4.5 0 001.242 7.244" />
                    </svg>
                  )}
                </div>

                <div className="flex-1 min-w-0 space-y-1">
                  {/* Platform selector */}
                  <select
                    value={link.platform}
                    onChange={(e) => update(i, 'platform', e.target.value)}
                    className="w-full bg-transparent text-xs font-semibold text-foreground focus:outline-none cursor-pointer"
                    style={{ color: meta?.color }}
                  >
                    {PLATFORMS.map((p) => (
                      <option key={p.name} value={p.name}>{p.name}</option>
                    ))}
                  </select>

                  {/* URL input */}
                  <input
                    type={link.platform === 'WeChat' ? 'text' : 'url'}
                    placeholder={meta?.placeholder ?? 'https://…'}
                    value={link.url}
                    onChange={(e) => update(i, 'url', e.target.value)}
                    className="w-full bg-transparent text-sm text-muted-foreground placeholder:text-muted-foreground/60 focus:outline-none focus:text-foreground"
                  />
                </div>
              </div>

              <button
                type="button"
                onClick={() => remove(i)}
                aria-label="Remove"
                className="text-muted-foreground hover:text-destructive transition-colors cursor-pointer opacity-0 group-hover:opacity-100 text-sm shrink-0"
              >
                ✕
              </button>
            </div>
          )
        })}
      </div>

      {links.length > 0 && (
        <p className="text-xs text-muted-foreground">
          {valid.length} of {links.length} link{links.length !== 1 ? 's' : ''} with a URL
        </p>
      )}
    </div>
  )
}
